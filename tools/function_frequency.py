"""Rank Excel's worksheet functions by how many workbooks of a corpus use them.

    uv run python tools/function_frequency.py CORPUS_DIRECTORY [-o tools/function_frequency.tsv]

Reads every ``.xlsx`` under the directory with the standard library (``formula_roundtrip.py``),
counts per function name the workbooks using it and its calls, keeps only Excel's own
functions (the names openpyxl knows, plus anything with Excel's ``_xlfn.`` prefix), and reports
add-in and workbook-defined functions only as totals, never by name. Writes a TSV ordered by
workbooks; ``tools/function_frequency.tsv`` is this script's output for the Enron corpus
(``tools/fetch_enron.py`` fetches it), followed by the newer functions that corpus cannot
contain, ranked by judgment.
"""

from __future__ import annotations

import argparse
import collections
import contextlib
import sys
from pathlib import Path

from openpyxl.utils import FORMULAE

sys.path.insert(0, str(Path(__file__).resolve().parent))

from formula_roundtrip import formulas
from xlrecalc._formula import Kind, TokenizeError, tokenize

HEADER = """\
# Excel worksheet functions ranked by the number of workbooks using them.
#
# Derived from the Enron spreadsheet corpus: F. Hermans and E. Murphy-Hill, "Enron's
# Spreadsheets and Related Emails: A Dataset and Analysis", MSR 2015; figshare,
# doi:10.6084/m9.figshare.1221767, licensed CC BY 4.0
# (https://creativecommons.org/licenses/by/4.0/). Changes: only aggregate counts per Excel
# function name were derived ({files} .xlsx files, {formulas} formula cells, {calls} function
# calls); nothing else from the corpus is included. Add-in and workbook-defined functions
# are counted only in total: {custom_names} names in {custom_files} workbooks.
#
# The corpus is from the early 2000s, so functions Excel added later are absent from the
# measured part, Excel 2007's included ({absent}).
# Those are ranked after it by judgment, not measurement; their counts say "judged".
#
# Generated by tools/function_frequency.py.
# columns: rank function workbooks calls (workbooks using the function; calls in all formulas)
"""

# Functions newer than the corpus, in the order judged most used today: lookup and the
# conditional aggregates first, then text joining, the dynamic-array family, LET and LAMBDA.
JUDGED = [
    "IFERROR", "SUMIFS", "COUNTIFS", "XLOOKUP", "AVERAGEIF", "AVERAGEIFS", "IFNA", "IFS",
    "MAXIFS", "MINIFS", "TEXTJOIN", "CONCAT", "FILTER", "UNIQUE", "SORT", "XMATCH", "SWITCH",
    "SEQUENCE", "LET", "SORTBY", "AGGREGATE", "TEXTSPLIT", "TEXTBEFORE", "TEXTAFTER", "VSTACK",
    "HSTACK", "TAKE", "DROP", "CHOOSECOLS", "CHOOSEROWS", "TOCOL", "TOROW", "LAMBDA", "MAP",
    "BYROW", "BYCOL", "REDUCE", "SCAN", "MAKEARRAY", "RANDARRAY", "WRAPROWS", "WRAPCOLS",
    "EXPAND", "DAYS", "ISOWEEKNUM", "FORMULATEXT", "ISFORMULA", "SHEET", "SHEETS",
]  # fmt: skip


EXCEL_2007 = ("IFERROR", "SUMIFS", "COUNTIFS", "AVERAGEIF", "AVERAGEIFS")


def _names(texts: list[str]) -> collections.Counter[str]:
    counts: collections.Counter[str] = collections.Counter()
    for text in texts:
        with contextlib.suppress(TokenizeError):
            counts.update(t.text.upper() for t in tokenize(text) if t.kind is Kind.FUNCTION)
    return counts


def _excel(name: str) -> bool:
    return name in FORMULAE or name.startswith("_XLFN.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("corpus", type=Path)
    parser.add_argument("-o", "--output", type=Path, default=Path(__file__).with_suffix(".tsv"))
    args = parser.parse_args()
    if not args.corpus.is_dir():
        print(f"{args.corpus}: not found (fetch it with tools/fetch_enron.py)")
        return 0
    files = sorted(args.corpus.rglob("*.xlsx"))
    workbooks: collections.Counter[str] = collections.Counter()
    cells: collections.Counter[str] = collections.Counter()
    custom_files = 0
    formula_cells = 0
    for path in files:
        texts = formulas(path)
        formula_cells += len(texts)
        counts = _names(texts)
        cells.update(counts)
        workbooks.update(counts.keys())
        custom_files += any(not _excel(n) for n in counts)
    excel = [n for n in workbooks if _excel(n)]
    excel.sort(key=lambda n: (-workbooks[n], -cells[n], n))
    custom = [n for n in workbooks if not _excel(n)]
    lines = [
        HEADER.format(
            files=len(files),
            formulas=formula_cells,
            calls=sum(cells.values()),
            custom_names=len(custom),
            custom_files=custom_files,
            absent=", ".join(n for n in EXCEL_2007 if n not in workbooks),
        ).rstrip("\n")
    ]
    lines += [f"{k}\t{n}\t{workbooks[n]}\t{cells[n]}" for k, n in enumerate(excel, 1)]
    measured = {n.removeprefix("_XLFN.") for n in excel}
    judged = [n for n in JUDGED if n not in measured]
    lines += [f"{len(excel) + k}\t{n}\tjudged\tjudged" for k, n in enumerate(judged, 1)]
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{args.output}: {len(excel)} measured, {len(judged)} judged, {len(custom)} custom names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
